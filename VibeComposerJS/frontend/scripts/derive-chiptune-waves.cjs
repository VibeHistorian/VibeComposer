// Maintenance only: reduce the reference's stationary loops to 400 Fourier partials.
// No samples or SF2 file are needed by the shipped application.
const fs = require('node:fs');
const path = require('node:path');
const { Sf2Bank } = require('./music-loader.cjs').loadMusic('../audio/sf2-resolver.ts');
const bytes = fs.readFileSync(path.join(__dirname, '../../chiptune_soundfont_4.0.sf2'));
const bank = new Sf2Bank(bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength));
const round = n => Number(n.toFixed(6));
const HARMONICS = 400;
const waves = {};
for (let id = 0; id < 19; id++) {
  const region = bank.presets.flatMap(p => p.regions).find(r => r.sampleId === id);
  const pcm = bank.pcm(region);
  const real = [0], imag = [0];
  // These nineteen one-second A1 loops have exactly 55 cycles, root MIDI 33.
  if (region.pitch !== 33 || pcm.length !== region.sampleRate) throw Error('Reference loop changed');
  if (55 * HARMONICS >= region.sampleRate / 2) throw Error('Harmonic limit exceeds source Nyquist frequency');
  for (let harmonic = 1; harmonic <= HARMONICS; harmonic++) {
    let cosine = 0, sine = 0;
    for (let i = 0; i < pcm.length; i++) {
      const phase = 2 * Math.PI * 55 * harmonic * i / region.sampleRate;
      cosine += pcm[i] * Math.cos(phase); sine += pcm[i] * Math.sin(phase);
    }
    real.push(round(2 * cosine / pcm.length)); imag.push(round(2 * sine / pcm.length));
  }
  waves['wChip' + id] = { real, imag };
}
const melodic = {};
for (const preset of bank.presets.filter(p => p.bank === 0)) {
  const r = preset.regions[0];
  if (preset.regions.length !== 1 || r.sampleId > 18) continue;
  // TinySynth's t is a frequency ratio, so cents remain constant across notes.
  // detune includes both preset fine tuning and the sample's pitch correction.
  melodic[preset.program] = [{ w: 'wChip' + r.sampleId, v: round(10 ** (r.volume / 20)),
    t: 2 ** ((r.tune * 100 + r.detune) / 1200),
    a: round(r.ampAttack), h: round(r.ampHold), d: round(r.ampDecay),
    s: round(r.ampSustain), r: round(r.ampRelease / 3.5),
    envelope: { delay: r.ampDelay, attack: r.ampAttack, hold: r.ampHold,
      decay: r.ampDecay, sustain: r.ampSustain, release: r.ampRelease } }];
}
const target = path.join(__dirname, '../src/app/core/audio/chiptune-reference.ts');
fs.writeFileSync(target, `// Generated by scripts/derive-chiptune-waves.cjs; see audio/README.md.\n`
  + `import type { SynthOperator } from './tiny-synth-engine';\n`
  + `export const CHIPTUNE_WAVES = ${JSON.stringify(waves, null, 0)};\n`
  + `export const CHIPTUNE_REFERENCE: Readonly<Record<number, readonly SynthOperator[]>> = ${JSON.stringify(melodic, null, 2)};\n`);
console.log(`Wrote ${Object.keys(waves).length} waves (${HARMONICS} harmonics each) and ${Object.keys(melodic).length} reference envelopes.`);
